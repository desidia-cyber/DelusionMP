#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Build the DelusionMP plugin and deploy it to every rig instance.

.DESCRIPTION
    Builds mod/DelusionMP.csproj against the interop assemblies generated by BepInEx
    in rig/instance1, then copies the plugin into <instance>/game/BepInEx/plugins
    for instances 1..Count. Instances must be stopped when deploying: Windows will
    not let the file be replaced while the game holds it.

.EXAMPLE
    ./tools/deploy.ps1
    ./tools/deploy.ps1 -Count 2
#>
[CmdletBinding()]
param(
    [int]$Count = 2,
    [string]$Configuration = 'Debug',
    [switch]$NoBuild
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot

if (-not $NoBuild) {
    Write-Host "=== build ===" -ForegroundColor Cyan
    dotnet build (Join-Path $Root 'mod\DelusionMP.csproj') -c $Configuration -v:q -nologo
    if ($LASTEXITCODE -ne 0) { throw "build failed" }
}

$out = Join-Path $Root "mod\bin\$Configuration\DelusionMP.dll"
if (-not (Test-Path $out)) { throw "missing build output: $out" }

for ($i = 1; $i -le $Count; $i++) {
    $plugins = Join-Path $Root "rig\instance$i\game\BepInEx\plugins"
    if (-not (Test-Path $plugins)) { Write-Warning "instance$i has no BepInEx/plugins"; continue }
    Copy-Item $out (Join-Path $plugins 'DelusionMP.dll') -Force
    Write-Host "  [ok] instance$i <- DelusionMP.dll" -ForegroundColor Green
}
